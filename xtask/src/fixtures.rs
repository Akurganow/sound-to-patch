//! Writes the generated `.vital` fixtures of `tests/fixtures/vital/`.
//!
//! Every file comes from our own code: the built-in template and the
//! writers of the library. `--check` compares the committed files with a
//! fresh run, so a change to the writers shows up as a fixture diff.

use std::fs;
use std::path::Path;

use sha2::{Digest, Sha256};

use crate::fetch::Sha256Digest;
use sound_to_patch::preset::format::{PresetFormat, PresetModel, Stored};
use sound_to_patch::preset::template::TemplateSource;
use sound_to_patch::preset::vital::{
    FORMAT, Keyframe, LfoShape, VitalModel, VitalTemplate, Wavetable,
};

/// Where the fixtures live, relative to the workspace root.
const DIR: &str = "tests/fixtures/vital";

/// The provenance table of every fixture, relative to the workspace root.
const PROVENANCE: &str = "tests/fixtures/PROVENANCE.md";

/// The size limit of one fixture.
const MAX_BYTES: u64 = 256 * 1024;

/// The line of `PROVENANCE.md` that lists the allowed wavetable authors.
const AUTHORS_LINE: &str = "Allowed wavetable authors: ";

/// The stamps of the version-gate set: the open source, a retail build, a
/// newer patch and a newer minor.
const STAMPS: [&str; 4] = ["1.0.6", "1.5.5", "1.0.9", "1.1.0"];

/// The smallest file Vital loads: the stamp and the three sample fields.
const MINIMAL: &str = r#"{"synth_version":"1.0.6","settings":{"sample":{"length":4,"sample_rate":44100,"samples":"AAAAAAAAAAA="}}}"#;

/// A file that marks every kind of odd value `preset inspect` reports.
const MARKS: &str = r#"{"synth_version":"1.0.6","preset_name":"marks","author":"sound-to-patch","comments":"A hand-written test file","preset_style":"Bass","settings":{"filter_1_on":1.0,"filter_1_cutoff":72.0,"filter_2_cutoff":140.0,"env_1_attack":0.5,"osc_1_transpose":-12.0,"sub_on":0.0,"zz_unknown":1,"custom_warps":[],"modulation_1_amount":0.25,"modulations":[{"source":"lfo_1","destination":"filter_1_cutoff"},{"source":"","destination":""},{"source":"","destination":""},{"source":"","destination":""},{"source":"","destination":""}],"sample":{"name":"Silence","length":4,"sample_rate":44100,"samples":"AAAAAAAAAAA="}},"extra_top":true}"#;

/// Every generated fixture as `(file name, bytes)`.
pub(crate) fn generate() -> crate::Result<Vec<(String, Vec<u8>)>> {
    let mut files = vec![
        ("minimal.vital".to_owned(), MINIMAL.as_bytes().to_vec()),
        ("marks.vital".to_owned(), MARKS.as_bytes().to_vec()),
        ("routes.vital".to_owned(), routes()?),
    ];
    for stamp in STAMPS {
        files.push((
            format!("stamps/{stamp}.vital"),
            MINIMAL.replacen("1.0.6", stamp, 1).into_bytes(),
        ));
    }
    Ok(files)
}

/// The built-in template with routes, an LFO shape, a two-frame wavetable
/// and a few controls.
fn routes() -> crate::Result<Vec<u8>> {
    let template = VitalTemplate
        .builtin()
        .ok_or("the Vital template has no built-in")?;
    let model = FORMAT.read(&template)?;
    let mut model = model
        .as_any()
        .downcast_ref::<VitalModel>()
        .ok_or("the Vital format read another model")?
        .clone();
    model.set_name("routes")?;
    model.set_description("Generated by cargo xtask vital-fixtures")?;
    model.set_tags(&["Bass".to_owned()])?;
    for (key, value) in [
        ("filter_1_on", 1.0),
        ("filter_1_cutoff", 72.0),
        ("filter_1_resonance", 0.3),
        ("osc_1_unison_voices", 3.0),
        ("env_2_decay", 0.5),
        ("reverb_on", 1.0),
    ] {
        model.set(key, Stored::Float(value))?;
    }
    model.route("lfo_1", "filter_1_cutoff", 0.25, None, None)?;
    model.route("env_2", "osc_1_level", 0.5, None, Some(-2.0))?;
    model.route("macro_control_1", "reverb_dry_wet", 0.75, None, None)?;
    model.set_macro_label(1, "Space")?;
    model.set_lfo_shape(
        0,
        &LfoShape {
            name: "Ramp Down".to_owned(),
            points: vec![(0.0, 0.0), (0.5, 0.5), (1.0, 1.0)],
            powers: vec![0.0, -2.0, 0.0],
            smooth: false,
        },
    )?;
    model.set_wavetable(
        0,
        &Wavetable {
            name: "Parabola to Square".to_owned(),
            author: "sound-to-patch".to_owned(),
            keyframes: vec![frame(0, parabola), frame(256, square)],
        },
    )?;
    Ok(FORMAT.write(&model)?)
}

/// One cycle of 2048 samples of `shape`, from phase 0 to just below 1.
fn frame(position: u16, shape: fn(f32) -> f32) -> Keyframe {
    let samples = (0..2048_u16)
        .map(|i| shape(f32::from(i) / 2048.0))
        .collect();
    Keyframe { position, samples }
}

/// A sine-like cycle of two parabola halves. It uses only exact IEEE
/// operations, so every platform writes the same bytes; `f32::sin` differs
/// between platform maths libraries in the last bits.
fn parabola(phase: f32) -> f32 {
    if phase < 0.5 {
        16.0 * phase * (0.5 - phase)
    } else {
        -16.0 * (phase - 0.5) * (1.0 - phase)
    }
}

/// A square cycle: +1 for the first half, -1 for the second.
fn square(phase: f32) -> f32 {
    if phase < 0.5 { 1.0 } else { -1.0 }
}

/// The SHA-256 of a file as 64 hex digits.
fn sha256(bytes: &[u8]) -> String {
    Sha256Digest(Sha256::digest(bytes).into()).to_string()
}

/// Writes the fixtures, or with `check` compares the committed ones and
/// refuses a committed file the generator does not produce.
pub(crate) fn run(root: &Path, check: bool) -> crate::Result<()> {
    let dir = root.join(DIR);
    let generated = generate()?;
    if check {
        let extra = orphans(&dir, &generated)?;
        if !extra.is_empty() {
            return Err(format!(
                "the generator does not produce these fixtures: {}. Add them to `generate` or remove them",
                extra.join(", ")
            )
            .into());
        }
    }
    let mut stale = Vec::new();
    for (name, bytes) in generated {
        let path = dir.join(&name);
        if check {
            if fs::read(&path).ok().as_deref() != Some(bytes.as_slice()) {
                stale.push(name);
            }
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(&path, &bytes)?;
            println!("{}  {DIR}/{name}  {} bytes", sha256(&bytes), bytes.len());
        }
    }
    if !stale.is_empty() {
        return Err(format!(
            "these fixtures differ from the generator: {}. Run `cargo xtask vital-fixtures` and update the SHA-256 rows of {PROVENANCE}",
            stale.join(", ")
        )
        .into());
    }
    if check {
        check_folder(&root.join("tests/fixtures"))?;
    }
    Ok(())
}

/// Checks every file under `vital/` against `PROVENANCE.md`: a row whose
/// SHA-256 matches, the size limit, a licence section for the folder, and
/// wavetable authors from the allowed list. The golden vectors carry their
/// own provenance, which `cargo xtask golden-check` checks.
pub(crate) fn check_folder(folder: &Path) -> crate::Result<()> {
    let provenance = fs::read_to_string(folder.join("PROVENANCE.md"))?;
    let authors: Vec<&str> = provenance
        .lines()
        .find_map(|line| line.strip_prefix(AUTHORS_LINE))
        .ok_or_else(|| format!("{PROVENANCE} has no line starting with {AUTHORS_LINE:?}"))?
        .trim_end_matches('.')
        .split(", ")
        .map(|name| name.trim_matches('`'))
        .collect();
    let mut problems = Vec::new();
    let mut files = Vec::new();
    list(folder, &folder.join("vital"), &mut files)?;
    for name in files {
        let bytes = fs::read(folder.join(&name))?;
        let row = provenance
            .lines()
            .find(|line| line.starts_with(&format!("| `{name}` |")));
        match row {
            None => problems.push(format!("{name} has no row")),
            Some(row) if !row.contains(&format!("`{}`", sha256(&bytes))) => {
                problems.push(format!(
                    "{name}: the SHA-256 of its row does not match the file"
                ));
            }
            Some(_) => {}
        }
        if u64::try_from(bytes.len()).is_ok_and(|size| size > MAX_BYTES) {
            problems.push(format!("{name} is larger than {MAX_BYTES} bytes"));
        }
        if let Some((top, _)) = name.split_once('/') {
            let mut chars = top.chars();
            let first = chars
                .next()
                .map(|c| c.to_uppercase().to_string())
                .unwrap_or_default();
            let heading = format!("## {first}{} fixtures", chars.as_str());
            if !provenance.lines().any(|line| line == heading) {
                problems.push(format!("{name} has no licence section {heading:?}"));
            }
        }
        if Path::new(&name)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("vital"))
        {
            for author in wavetable_authors(&bytes)? {
                if !authors.contains(&author.as_str()) {
                    problems.push(format!(
                        "{name}: wavetable author {author:?} is not allowed"
                    ));
                }
            }
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "{PROVENANCE} does not cover the fixtures: {}. Add or fix the rows, the licence section or the allowed authors",
            problems.join("; ")
        )
        .into())
    }
}

/// The files under `dir` that are not in `generated`.
fn orphans(dir: &Path, generated: &[(String, Vec<u8>)]) -> crate::Result<Vec<String>> {
    let mut files = Vec::new();
    list(dir, dir, &mut files)?;
    files.retain(|file| !generated.iter().any(|(name, _)| name == file));
    Ok(files)
}

/// Every file under `dir` except `PROVENANCE.md`, as a path relative to
/// `base` with `/` separators, sorted.
fn list(base: &Path, dir: &Path, files: &mut Vec<String>) -> crate::Result<()> {
    let mut entries = fs::read_dir(dir)?.collect::<std::io::Result<Vec<_>>>()?;
    entries.sort_by_key(fs::DirEntry::path);
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            list(base, &path, files)?;
        } else if path.file_name().is_some_and(|name| name != "PROVENANCE.md") {
            let relative = path.strip_prefix(base)?;
            files.push(
                relative
                    .components()
                    .map(|part| part.as_os_str().to_string_lossy())
                    .collect::<Vec<_>>()
                    .join("/"),
            );
        }
    }
    Ok(())
}

/// Prints every registry key that no generated fixture holds in its
/// settings. The list shows which controls the fixtures never exercise.
pub(crate) fn coverage() -> crate::Result<()> {
    let mut held = std::collections::BTreeSet::new();
    for (_, bytes) in generate()? {
        let preset: serde_json::Value = serde_json::from_slice(&bytes)?;
        if let Some(settings) = preset
            .get("settings")
            .and_then(serde_json::Value::as_object)
        {
            held.extend(settings.keys().cloned());
        }
    }
    let registry =
        sound_to_patch::preset::registry::registry_for(sound_to_patch::synth::Synth::Vital)?;
    let missing: Vec<&str> = registry
        .iter()
        .map(|spec| spec.key.as_str())
        .filter(|key| !held.contains(*key))
        .collect();
    println!(
        "{} of {} registry keys are in no fixture",
        missing.len(),
        registry.iter().count()
    );
    for key in missing {
        println!("{key}");
    }
    Ok(())
}

/// The `author` of every wavetable in a `.vital` file.
fn wavetable_authors(bytes: &[u8]) -> crate::Result<Vec<String>> {
    let preset: serde_json::Value = serde_json::from_slice(bytes)?;
    Ok(preset
        .pointer("/settings/wavetables")
        .and_then(serde_json::Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|table| table.get("author"))
        .map(|author| author.as_str().unwrap_or_default().to_owned())
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_fixtures_match_the_generator() {
        run(crate::root(), true).unwrap();
    }

    /// A copy of the committed fixture folder to break one rule in.
    fn folder_copy() -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        let source = crate::root().join("tests/fixtures");
        let mut files = Vec::new();
        list(&source, &source.join("vital"), &mut files).unwrap();
        files.push("PROVENANCE.md".to_owned());
        for name in files {
            let to = dir.path().join(&name);
            fs::create_dir_all(to.parent().unwrap()).unwrap();
            fs::copy(source.join(&name), to).unwrap();
        }
        dir
    }

    fn folder_error(dir: &tempfile::TempDir) -> String {
        check_folder(dir.path()).unwrap_err().to_string()
    }

    #[test]
    fn the_committed_folder_passes() {
        check_folder(&crate::root().join("tests/fixtures")).unwrap();
    }

    #[test]
    fn a_fixture_the_generator_does_not_produce_fails() {
        let dir = folder_copy();
        let vital = dir.path().join("vital");
        assert_eq!(
            orphans(&vital, &generate().unwrap()).unwrap(),
            Vec::<String>::new()
        );
        fs::write(vital.join("stamps/9.9.9.vital"), MINIMAL).unwrap();
        assert_eq!(
            orphans(&vital, &generate().unwrap()).unwrap(),
            ["stamps/9.9.9.vital"]
        );
        let root = tempfile::tempdir().unwrap();
        let fixtures = root.path().join("tests");
        fs::create_dir_all(&fixtures).unwrap();
        fs::rename(dir.path(), fixtures.join("fixtures")).unwrap();
        let error = run(root.path(), true).unwrap_err().to_string();
        assert!(
            error.contains("the generator does not produce these fixtures: stamps/9.9.9.vital"),
            "{error}"
        );
    }

    #[test]
    fn a_file_without_a_row_fails() {
        let dir = folder_copy();
        fs::write(dir.path().join("vital/extra.vital"), MINIMAL).unwrap();
        assert!(folder_error(&dir).contains("vital/extra.vital has no row"));
    }

    #[test]
    fn a_changed_file_fails() {
        let dir = folder_copy();
        fs::write(dir.path().join("vital/minimal.vital"), MARKS).unwrap();
        assert!(folder_error(&dir).contains("vital/minimal.vital: the SHA-256"));
    }

    #[test]
    fn a_missing_licence_section_fails() {
        let dir = folder_copy();
        let path = dir.path().join("PROVENANCE.md");
        let text = fs::read_to_string(&path)
            .unwrap()
            .replace("## Vital fixtures", "## Other");
        fs::write(path, text).unwrap();
        assert!(folder_error(&dir).contains("no licence section \"## Vital fixtures\""));
    }

    #[test]
    fn an_oversized_file_fails() {
        let dir = folder_copy();
        let big = vec![b' '; usize::try_from(MAX_BYTES).unwrap() + 1];
        let path = dir.path().join("vital/minimal.vital");
        let mut bytes = MINIMAL.as_bytes().to_vec();
        bytes.extend_from_slice(&big);
        fs::write(&path, &bytes).unwrap();
        assert!(folder_error(&dir).contains("vital/minimal.vital is larger than 262144 bytes"));
    }

    #[test]
    fn a_foreign_wavetable_author_fails() {
        let dir = folder_copy();
        let path = dir.path().join("vital/routes.vital");
        let text = fs::read_to_string(&path).unwrap().replace(
            "\"author\":\"sound-to-patch\"",
            "\"author\":\"Someone Else\"",
        );
        fs::write(path, text).unwrap();
        assert!(folder_error(&dir).contains("wavetable author \"Someone Else\" is not allowed"));
    }

    #[test]
    fn the_generator_is_deterministic() {
        assert_eq!(generate().unwrap(), generate().unwrap());
    }
}
